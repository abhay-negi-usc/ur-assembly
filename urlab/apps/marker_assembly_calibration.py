"""MARKER ASSEMBLY CALIBRATION -- where a held object sits on a fixed one, measured by sight.

    python -m urlab.apps.marker_assembly_calibration --set marker_assembly=tile_on_plate

Writes one entry into configs/marker_assemblies.yaml: for every marker on the FIXED object, the
HELD object's mating frame at its assembled position, in that marker's own frame.
apps/coupler_marker_assemble drives to it.

VISUAL, NOTHING HELD. Assemble the two objects BY HAND, then let the camera look at both. One
sweep sees the fixed object's markers and the held object's markers together, so

    T_base_goal  = T_base_held_marker @ T_held_marker_grasp     (objects.yaml, voted + joint PnP)
    T_fixed_goal = inverse(T_base_fixed_marker) @ T_base_goal   (per fixed marker)

The robot only carries the camera, and base_link cancels: both markers are measured from the
same views, so what is stored is purely a relationship between the two objects.

WHAT THAT INHERITS. The held object's grasp offsets come from its objects.yaml calibration, so
an error there is baked into every entry measured through it -- re-run urlab.apps.
object_calibration before this if that object's markers were moved. The fixed object's markers
need no prior calibration: this run IS their calibration.

CAPTURES. Each capture returns to the same view and sweeps again. Between captures you are asked
to RE-SEAT the held object; the spread across captures is then how repeatably the assembly
seats, plus marker noise. Leaving it in place measures marker noise alone.

START POSE. `start_joints_deg`, when set, is moved to ONCE before anything else -- a known
place to begin from, near the scene; the hand-guiding (or the move to view_joints_deg) starts
there.

THE VIEW POSE IS RECORDED. Unless `record_view_joints: false`, the joints the markers were seen
from are written with the entry, and the run-time app looks at the fixed object from there:
seeing it from the same place cancels the part of the error that depends on viewpoint.

Output: data/experiments/marker_assembly_calibration_<stamp>/ -- the yaml entry, a per-capture
CSV and marker_images/. The catalogue is MERGED (other assemblies left alone) and the previous
version is backed up into the run directory first.
"""

